#arithmatic operators

x = 10
y = 5
sum = x+y
diff = x-y
product = x*y
division = x/y
remainder = x%y
power = x**y
print(sum,diff,product,division,remainder,power)

#comparision operator
print(x==y)
print(x>=y)
print(x<=y) #false
print(x!=y) #true
print(x>y)
print(x<y)

#logical operators

print(x<=y and x!=y)
print(x<=y or x!=y)
print(x!=y and x!=y)
print(not (x<=y))

